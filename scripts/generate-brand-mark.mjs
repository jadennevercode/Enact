#!/usr/bin/env node
/**
 * Fan the Enact brand mark out from its one source file.
 *
 *   node scripts/generate-brand-mark.mjs
 *
 * Source:  design-system/enact/mark-source.svg — the vector mark as supplied
 *          by brand (three paths, one vertical green gradient). Edit that file,
 *          never the outputs.
 *
 * Outputs (every one is overwritten in full):
 *   packages/ui/components/common/enact-mark-path.ts   web + desktop component
 *   apps/mobile/components/brand/enact-mark-path.ts    mobile component (mobile
 *                                                      may not import @enact/ui,
 *                                                      so it gets its own copy)
 *   apps/docs/app/enact-mark-path.ts                   docs site nav mark
 *   apps/web/public/favicon.svg                        browser tab, transparent
 *   docs/assets/logo-light.svg, logo-dark.svg          README / VISION marks
 *   apps/web/public/icons/icon.svg                     full-bleed app-icon source
 *
 * After running this, run `node scripts/generate-brand-icons.mjs` to rasterise
 * icon.svg into the PWA, desktop and mobile icon sets. The colour stops also
 * live as `--mark-from` / `--mark-mid` / `--mark-to` in
 * packages/ui/styles/tokens.css; apps/web/app/brand-mark-sync.test.ts checks
 * that every copy agrees with the source.
 *
 * The path data is copied verbatim, in the source's own coordinate space, so
 * that every copy holds the byte-identical string and the sync test can
 * compare strings instead of geometry.
 */
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "design-system/enact/mark-source.svg";

/** Fraction of the app-icon canvas the mark's visible extent occupies. */
const APP_ICON_MARK_SCALE = 0.62;
const APP_ICON_SIZE = 512;

const svg = readFileSync(SOURCE, "utf8");

const viewBox = /viewBox="([^"]+)"/.exec(svg)?.[1];
if (!viewBox) throw new Error(`${SOURCE}: no viewBox`);
const [vbX, vbY, vbW, vbH] = viewBox.split(/\s+/).map(Number);
if (vbX !== 0 || vbY !== 0 || vbW !== vbH) {
  throw new Error(`${SOURCE}: expected a square viewBox at the origin, got "${viewBox}"`);
}

const paths = [...svg.matchAll(/<path\b[^>]*\bd="([^"]+)"/g)].map((m) =>
  m[1].trim().replace(/\s+/g, " "),
);
if (paths.length === 0) throw new Error(`${SOURCE}: no <path> elements`);
const markPath = paths.join(" ");

const gradient = /<linearGradient\b([^>]*)>([\s\S]*?)<\/linearGradient>/.exec(svg);
if (!gradient) throw new Error(`${SOURCE}: no <linearGradient>`);
const attr = (name) => {
  const v = new RegExp(`\\b${name}="([^"]+)"`).exec(gradient[1])?.[1];
  if (v === undefined) throw new Error(`${SOURCE}: gradient has no ${name}`);
  return Number(v);
};
const gradientBox = { x1: attr("x1"), y1: attr("y1"), x2: attr("x2"), y2: attr("y2") };

const stops = [...gradient[2].matchAll(/<stop\b[^>]*offset="([^"]+)"[^>]*stop-color="([^"]+)"/g)].map(
  (m) => [parseFloat(m[1]) / (m[1].endsWith("%") ? 100 : 1), m[2].toLowerCase()],
);
const stopAt = (offset) => {
  const hit = stops.find(([o]) => Math.abs(o - offset) < 1e-6);
  if (!hit) throw new Error(`${SOURCE}: gradient has no stop at ${offset}`);
  return hit[1];
};
// Three stops reproduce the source's eased ramp to within a few units of
// sRGB at every quarter; the ends stay on the palette.
const markStops = { from: stopAt(0), mid: stopAt(0.5), to: stopAt(1) };

// --- generated TypeScript constants -------------------------------------

const tsModule = `// Generated by scripts/generate-brand-mark.mjs from ${SOURCE}.
// Do not edit; change the source and re-run the script.

/** viewBox of the mark's own coordinate space. */
export const ENACT_MARK_VIEWBOX = "${viewBox}";

/** Every visible part of the mark as one path, filled with a single colour or gradient. */
export const ENACT_MARK_PATH =
  "${markPath}";

/** Gradient axis in ENACT_MARK_VIEWBOX units (userSpaceOnUse). */
export const ENACT_MARK_GRADIENT = {
  x1: ${gradientBox.x1},
  y1: ${gradientBox.y1},
  x2: ${gradientBox.x2},
  y2: ${gradientBox.y2},
} as const;

/**
 * Colour-variant stops at 0 / 0.5 / 1. Web and desktop read these through the
 * \`--mark-from\` / \`--mark-mid\` / \`--mark-to\` tokens in
 * packages/ui/styles/tokens.css; mobile and the static SVGs use the literals.
 */
export const ENACT_MARK_STOPS = {
  from: "${markStops.from}",
  mid: "${markStops.mid}",
  to: "${markStops.to}",
} as const;
`;

for (const out of [
  "packages/ui/components/common/enact-mark-path.ts",
  "apps/mobile/components/brand/enact-mark-path.ts",
  "apps/docs/app/enact-mark-path.ts",
]) {
  writeFileSync(out, tsModule);
  console.log(out);
}

// --- static SVGs ---------------------------------------------------------

const gradientDefs = (id) =>
  `  <defs>
    <linearGradient id="${id}" gradientUnits="userSpaceOnUse" x1="${gradientBox.x1}" y1="${gradientBox.y1}" x2="${gradientBox.x2}" y2="${gradientBox.y2}">
      <stop offset="0" stop-color="${markStops.from}"/>
      <stop offset="0.5" stop-color="${markStops.mid}"/>
      <stop offset="1" stop-color="${markStops.to}"/>
    </linearGradient>
  </defs>`;

const transparentMark = (id, comment) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" role="img" aria-label="Enact">
  <!--
    Generated by scripts/generate-brand-mark.mjs from ${SOURCE}; do not edit.
    ${comment}
  -->
${gradientDefs(id)}
  <path fill="url(#${id})" d="${markPath}"/>
</svg>
`;

writeFileSync(
  "apps/web/public/favicon.svg",
  transparentMark(
    "enact-favicon",
    "The Enact mark in its colour variant on a transparent ground, so the tab\n    icon sits on whatever the browser paints behind it, light or dark.",
  ),
);
console.log("apps/web/public/favicon.svg");

for (const theme of ["light", "dark"]) {
  writeFileSync(
    `docs/assets/logo-${theme}.svg`,
    transparentMark(
      `enact-logo-${theme}`,
      "The Enact mark in its colour variant on a transparent ground. The colour\n    mark never follows the theme, so logo-light.svg and logo-dark.svg are\n    identical; both exist so <picture> sources can name one per scheme.",
    ),
  );
  console.log(`docs/assets/logo-${theme}.svg`);
}

// App icon: the mark's visible extent (its gradient box height) is scaled to
// APP_ICON_MARK_SCALE of the canvas and centred. The plate and the two shell
// lights are the light shell treatment from design-system/enact/MASTER.md §10.
const markExtent = gradientBox.y2 - gradientBox.y1;
const scale = (APP_ICON_SIZE * APP_ICON_MARK_SCALE) / markExtent;
const translate = (APP_ICON_SIZE - vbW * scale) / 2;
const fmt = (n) => n.toFixed(4).replace(/\.?0+$/, "");

writeFileSync(
  "apps/web/public/icons/icon.svg",
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${APP_ICON_SIZE} ${APP_ICON_SIZE}" role="img" aria-label="Enact">
  <!--
    Generated by scripts/generate-brand-mark.mjs from ${SOURCE}; do not edit.
    Full-bleed source for the generated home-screen icons (apple-touch-icon.png,
    icon-maskable-512.png) and for the desktop app icons. Full-bleed because
    every surface masks the artwork itself: iOS rounds the corners, Android
    crops to the launcher shape, macOS applies the squircle.
    The ground is the light shell treatment: Light Gray #f7f7f6 with the two
    static shell lights, Deloitte Green from the top-left corner and Green 2
    from the bottom-right, and never dark (MASTER.md §10). The mark is held at
    ${Math.round(APP_ICON_MARK_SCALE * 100)}% of the canvas so it stays inside the maskable safe zone (the centre
    circle of 80% diameter). See app/manifest.ts for the regeneration commands.
  -->
  <defs>
    <radialGradient id="enact-icon-light-a" gradientUnits="userSpaceOnUse" cx="0" cy="0" r="460">
      <stop offset="0" stop-color="#86bc25" stop-opacity="0.28"/>
      <stop offset="1" stop-color="#86bc25" stop-opacity="0"/>
    </radialGradient>
    <radialGradient id="enact-icon-light-b" gradientUnits="userSpaceOnUse" cx="${APP_ICON_SIZE}" cy="${APP_ICON_SIZE}" r="460">
      <stop offset="0" stop-color="#c4d600" stop-opacity="0.18"/>
      <stop offset="1" stop-color="#c4d600" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="enact-icon-mark" gradientUnits="userSpaceOnUse" x1="${gradientBox.x1}" y1="${gradientBox.y1}" x2="${gradientBox.x2}" y2="${gradientBox.y2}">
      <stop offset="0" stop-color="${markStops.from}"/>
      <stop offset="0.5" stop-color="${markStops.mid}"/>
      <stop offset="1" stop-color="${markStops.to}"/>
    </linearGradient>
  </defs>
  <rect width="${APP_ICON_SIZE}" height="${APP_ICON_SIZE}" fill="#f7f7f6"/>
  <rect width="${APP_ICON_SIZE}" height="${APP_ICON_SIZE}" fill="url(#enact-icon-light-a)"/>
  <rect width="${APP_ICON_SIZE}" height="${APP_ICON_SIZE}" fill="url(#enact-icon-light-b)"/>
  <g transform="translate(${fmt(translate)} ${fmt(translate)}) scale(${fmt(scale)})">
    <path fill="url(#enact-icon-mark)" d="${markPath}"/>
  </g>
</svg>
`,
);
console.log("apps/web/public/icons/icon.svg");
